// 对话页的排版数值,全部抄自 `open-vetta-conversation-spec.md`(下称"规格")。
//
// 为什么单独立一份而不是散在 chat_list / user_bubble 里:这些数字是**成组
// 出现的**(768 列宽配 20 内距、20 行距配 36 收尾),拆开写会各自漂移。
// 而且其中几条我们**故意不照搬**,写在一处才能看清哪条是规格、哪条是我们的
// 取舍(见每条注释)。

import '../../kit/kit.dart';

abstract final class ChatMetrics {
  // ── 消息列(规格 §1.2)────────────────────────────────────────────────

  /// 规格 `mx-auto max-w-3xl` = **768**。
  ///
  /// 我们用 AppSpace.readingWidth = 720,和 DSH 官方
  /// `--dsh-chat-content-width: 748` 同档。**不改成 768**:阅读列是整站的
  /// 一套(顶栏、输入条、斜杠面板、其它页面都按它居中),只有对话页宽 48px
  /// 会和其他页面错位;720 与 768 在手机上也没有差别(视口更窄)。
  static const specColumnWidth = 768.0;

  /// 规格列内距 `px-5` = **20**。
  ///
  /// 我们沿用 AppSpace.gutter = 16(全站页面留白)。改成 20 要连输入条的
  /// AppSpace.floatInset 一起改,否则消息正文和输入卡左右各差 4px、读起来
  /// 是歪的;那是跨页面的改动,不在这次的范围里。
  static const specColumnInset = 20.0;

  // ── 行距(规格 §1.2 的 `MessageRow`)──────────────────────────────────

  /// 规格常规行 `pb-5` = **20**。
  ///
  /// 我们只在"用户气泡 → 回复"这一处用它:全局换成 20 会把过程行(工具、
  /// 思考)之间 0/8 的节奏一起撑开,那是另一套密度设计,不是这次的观感修正。
  static const rowGap = 20.0;

  /// 规格"最后一条是用户消息"时 `pb-9` = **36**(给气泡下方的操作条留位)。
  ///
  /// 我们的行距是"下一行自己的上间距",末尾没有下一行,所以这条目前落在
  /// 输入条那一侧(由 `_ChatLayout.overlap` 和输入卡的内距承担)。
  static const specLastUserGap = 36.0;

  // ── 滚动(规格 §1.5)────────────────────────────────────────────────

  /// 规格 `atBottomThreshold={80}`:距底 ≤ 80 视为"还在底部"。
  ///
  /// **没有采用**。规格那边是桌面端的软跟随(每帧 lerp 0.045–0.28),80 是
  /// 它"还算在底部"的宽恕带;我们这边是"严格贴底才跟随"(离底任何一点都
  /// 不追),所以取 24 那一档(`chat_list.dart` 的 `_jumpHideReach`,和
  /// `_atBottom` 的默认值同一个数):一旦在离底 80px 处仍算贴底,用户往上读
  /// 的时候新内容会把他拽回去。这条被 `test/chat/jump_hysteresis_test.dart`
  /// 钉住,改它要连测试一起改。
  static const specBottomSlop = 80.0;

  /// 规格 `SCROLL_TO_BOTTOM_VISIBILITY_THRESHOLD_PX = 500`。
  ///
  /// 我们保留 160:那是 768 宽桌面上"不到一屏"的距离,手机上视口只有
  /// 600–800,500 已经超过大半屏,按钮几乎不会出现(等于去掉这个功能)。
  /// 这条留在报告里当待定项,不在本次改动中。
  static const specScrollToBottomThreshold = 500.0;

  // ── 气泡(规格 §2.1)────────────────────────────────────────────────

  /// 规格乐观气泡 `data-[pending=true]:opacity-70`:整泡 70%。
  ///
  /// 用 mute 阶梯里的现成一档,不要写 0.72 这种"看上去差不多"的数。
  static const pendingOpacity = KitMuted.a70;
}
